#!/usr/bin/env node
/**
 * Playwright pin agreement — agent/package.json ↔ agent/package-lock.json ↔ root
 * package-lock.json.
 *
 * ## Why this exists
 *
 * `agent/Dockerfile` states the invariant in prose:
 *
 *   > The pin tracks the root package-lock.json, because e2e/tests/driver.spec.ts
 *   > runs driver.mjs from the HOST — so the root lock is the Playwright that has
 *   > actually driven Foundry.
 *   > ⚠️ Bump BOTH together, and re-run `npm run e2e`; they are one decision.
 *
 * Nothing enforced it. A comment is not a guard, and this repo has already paid
 * for that distinction twice — the `abandoned` denylist and the base digest that
 * "read as pinned" while Playwright floated a layer below it.
 *
 * ## What each existing guard does NOT cover
 *
 * `npm ci` (added at v0.3.1) compares agent/package.json against
 * agent/package-lock.json and hard-fails on a mismatch. That is one edge of a
 * triangle. It says nothing about the ROOT lock, so the documented coupling can
 * still break in silence: bump the root and the image keeps building green
 * against a Playwright no e2e run has ever exercised, or bump the agent and the
 * host-run driver spec silently tests a different browser than the one shipped.
 *
 * Neither direction fails anything today. That is the whole problem — it is the
 * v0.3.0 shape exactly: green builds, a `:latest` the launcher pulls with
 * `imagePull: always`, and a divergence nobody looked for because the file above
 * it read as pinned.
 *
 * ## Why an EXACT spec is checked too
 *
 * v0.3.0's actual fault was `"@playwright/test": "^1.49.0"` with no lockfile, so
 * every build re-resolved and `playwright install chromium` followed it
 * (1.61.0 → 1.62.1, Chromium 149 → 151). A range here reintroduces that even
 * with a lock present, because the lock can be regenerated by any `npm install`.
 *
 * Pure + offline: `comparePins` takes the three values and returns problems, so
 * the interesting cases are testable without a registry, a network or Docker.
 */
import { readFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const AGENT_DIR = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(AGENT_DIR, '..')

const PKG = '@playwright/test'
const LOCK_KEY = `node_modules/${PKG}`

/** A version the lockfile could not supply is `null`, never a guessed string. */
function lockedVersion(lockPath) {
  const lock = JSON.parse(readFileSync(lockPath, 'utf8'))
  return lock.packages?.[LOCK_KEY]?.version ?? null
}

/**
 * The whole decision, as a pure function.
 *
 * ⚠️ A missing lock entry is a PROBLEM, not a skip. "Could not read it" and
 * "it agrees" must never collapse into the same verdict — that collapse is the
 * bug pattern this repo keeps re-finding, most recently a registry 401 that
 * rendered as "network unreachable" and passed.
 */
export function comparePins({ agentSpec, agentLock, rootLock }) {
  const problems = []

  if (!agentSpec) {
    problems.push(`agent/package.json declares no ${PKG} dependency`)
  } else if (!/^\d+\.\d+\.\d+$/.test(agentSpec)) {
    problems.push(
      `agent/package.json pins ${PKG} as "${agentSpec}" — must be an EXACT version.\n` +
        '  A range re-resolves on any `npm install`, and `playwright install chromium`\n' +
        '  follows it, swapping the browser this driver steers Foundry with. That is\n' +
        '  the v0.3.0 fault verbatim.',
    )
  }

  for (const [label, value] of [
    ['agent/package-lock.json', agentLock],
    ['package-lock.json (root)', rootLock],
  ]) {
    if (!value) problems.push(`${label} has no ${LOCK_KEY} entry — cannot verify the pin, so this is a FAILURE, not a skip`)
  }

  // Only compare once every value is present; a null would otherwise report as
  // a mismatch and bury the real "missing entry" message above.
  //
  // The SPEC joins the comparison only when it is an exact version. A range has
  // already been reported above, and folding it in here too would print "pins
  // disagree: ^1.61.0 vs 1.61.0 vs 1.61.0" — two messages for one fault, the
  // second of them describing a version disagreement that does not exist.
  if (agentLock && rootLock) {
    const comparable = [agentLock, rootLock]
    if (agentSpec && /^\d+\.\d+\.\d+$/.test(agentSpec)) comparable.push(agentSpec)
    const distinct = new Set(comparable)
    if (distinct.size > 1) {
      problems.push(
        `${PKG} pins disagree:\n` +
          `    agent/package.json        ${agentSpec}\n` +
          `    agent/package-lock.json   ${agentLock}\n` +
          `    package-lock.json (root)  ${rootLock}\n` +
          '  agent/Dockerfile requires these to move together: the root lock is the\n' +
          '  Playwright that e2e/tests/driver.spec.ts actually runs on the HOST, and the\n' +
          '  agent pair is what ships inside cfg-foundry-service-gm — which the launcher\n' +
          '  pulls with imagePull: always on EVERY user container launch.\n' +
          '  Bump all three, then re-run `npm run e2e`. They are one decision.',
      )
    }
  }

  return problems
}

function main() {
  const agentSpec = JSON.parse(readFileSync(join(AGENT_DIR, 'package.json'), 'utf8')).dependencies?.[PKG] ?? null
  const agentLock = lockedVersion(join(AGENT_DIR, 'package-lock.json'))
  const rootLock = lockedVersion(join(REPO_ROOT, 'package-lock.json'))

  const problems = comparePins({ agentSpec, agentLock, rootLock })
  if (problems.length) {
    console.error('\n✗ Playwright pin disagreement\n')
    for (const p of problems) console.error(`  ${p}\n`)
    process.exit(1)
  }
  console.log(`✓ ${PKG} pinned at ${agentSpec} across agent/package.json, agent lock and the root lock`)
}

// Importing this module for its pure half must not run the check or print.
if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) main()
